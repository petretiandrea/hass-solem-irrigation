"""BLE adapter contract. Implementations must keep I/O off the event loop."""
from typing import Callable, Protocol


class BLETransport(Protocol):
    async def connect(self) -> object: ...
    async def disconnect(self) -> object: ...
    async def start_notify(self, uuid: str, callback: Callable[[object, bytearray], None], /) -> object: ...
    async def stop_notify(self, uuid: str, /) -> object: ...
    async def read_gatt_char(self, uuid: str, /) -> bytearray: ...
    async def write_gatt_char(self, uuid: str, data: bytes, /, *, response: bool) -> object: ...
